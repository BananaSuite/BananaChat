def get_language():
    if has_request_context():
        override = getattr(g, "_language_override", None)
        if override in SUPPORTED_LANGUAGES:
            return override
    value = session.get("language", DEFAULT_LANGUAGE)
    return value if value in SUPPORTED_LANGUAGES else DEFAULT_LANGUAGE


def translate(key):
    lang = get_language()
    return _STRINGS.get(lang, _STRINGS[DEFAULT_LANGUAGE]).get(
        key, _STRINGS["en"].get(key, key)
    )


def browser_strings():
    return dict(_STRINGS[get_language()])
